from datetime import datetime, timezone
from typing import Dict, Any, List, Optional
from app.ai.base_provider import BaseLLMProvider
from app.ai.response_validator import validate_and_sanitize_response

class FallbackFinancialAIProvider(BaseLLMProvider):
    """
    Deterministic, high-quality offline financial intelligence provider.
    Ensures 100% application functionality even without external API credentials.
    """

    def generate_chat_response(
        self,
        messages: List[Dict[str, str]],
        context_data: Optional[Dict[str, Any]] = None,
        system_prompt: Optional[str] = None
    ) -> Dict[str, Any]:
        last_message = messages[-1]["content"].lower() if messages else ""
        citations = []
        
        # Context extraction
        instrument_sym = ""
        price_str = ""
        if context_data and "instrument" in context_data:
            inst = context_data["instrument"]
            instrument_sym = inst.get("symbol", "")
            price = inst.get("current_price", 0.0)
            currency = inst.get("currency", "INR")
            price_str = f"{currency} {price:,.2f}"
            citations.append({
                "title": f"{instrument_sym} Market Quote",
                "source": f"{inst.get('exchange_code', 'Exchange')} Data Feed",
                "data_timestamp": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
                "confidence": 1.0
            })

        # Knowledge base routing
        if "pe ratio" in last_message or "p/e" in last_message or "price to earnings" in last_message:
            content = (
                "**Price-to-Earnings (P/E) Ratio Explained:**\n\n"
                "The P/E ratio measures a company's current share price relative to its per-share earnings (EPS).\n\n"
                "- **Formula:** `P/E Ratio = Market Price per Share / Earnings Per Share (EPS)`\n"
                "- **Interpretation:** A P/E of 25 means investors are paying ₹25 (or $25) for every ₹1 (or $1) of annual earnings generated by the business.\n"
                "- **Trailing P/E vs. Forward P/E:** Trailing uses past 12-month audited earnings, while Forward uses consensus analyst forecasts.\n"
                "- **Context Matters:** High P/E often indicates strong growth expectations (e.g. Technology/Cloud), whereas low P/E may reflect mature, slower-growth or cyclical industries (e.g. Utilities, Banking)."
            )
            citations.append({"title": "Financial Ratio Standards", "source": "FinPilot Financial Education Library", "confidence": 1.0})

        elif "market" in last_message and "limit order" in last_message:
            content = (
                "**Market Order vs. Limit Order:**\n\n"
                "1. **Market Order:**\n"
                "   - **Objective:** Immediate execution speed over price guarantee.\n"
                "   - **Behavior:** Fills instantly against best available bid/ask on the order book.\n"
                "   - **Risk:** High slippage during volatile market openings or illiquid instruments.\n\n"
                "2. **Limit Order:**\n"
                "   - **Objective:** Price control over guaranteed execution.\n"
                "   - **Behavior:** Executes only at your specified limit price or better. If the market does not reach your price, the order remains resting or expires.\n"
                "   - **Best Practice:** Professional traders utilize limit orders to prevent adverse slippage and enforce strict trade entry discipline."
            )
            citations.append({"title": "Order Execution Mechanics", "source": "Exchange Microstructure Guide", "confidence": 1.0})

        elif "diversification" in last_message or "portfolio" in last_message and "risk" in last_message:
            content = (
                "**Portfolio Diversification & Risk Allocation:**\n\n"
                "Diversification is the quantitative practice of spreading capital across uncorrelated assets, sectors, and geographies to reduce unsystematic (company-specific) risk without proportionately sacrificing expected returns.\n\n"
                "- **Core Principle:** According to Modern Portfolio Theory (Markowitz), when assets have correlation coefficients `ρ < 1.0`, portfolio variance decreases.\n"
                "- **Concentration Metric:** FinPilot calculates the Herfindahl-Hirschman Index (HHI). An HHI < 1,500 indicates healthy diversification; an HHI > 2,500 signals high single-asset risk.\n"
                "- **Rule of Thumb:** Limit single-stock allocation to 5–10% of total portfolio equity and sector exposure to <25%."
            )
            citations.append({"title": "Modern Portfolio Theory", "source": "FinPilot Risk Engine Documentation", "confidence": 1.0})

        elif "why did" in last_message and ("fall" in last_message or "drop" in last_message or "rise" in last_message or "move" in last_message):
            sym = instrument_sym or "the stock"
            content = (
                f"**Analysis of recent price movement for {sym}:**\n\n"
                f"Based on latest market data ({price_str if price_str else 'current trading levels'}), price action is primarily driven by three interacting catalysts:\n\n"
                "1. **Earnings & Multiple Re-rating:** Shifts in quarterly margin forecasts and sector multiple compression.\n"
                "2. **Institutional Flow & Liquidity:** Large block trades and foreign institutional investor (FII/DII) rebalancing across benchmark indices.\n"
                "3. **Macro Headwinds / Tailwinds:** Interest rate trajectory, bond yield movements, and commodity input price fluctuations.\n\n"
                "Check the **AI Stock Research** tab for detailed fundamental breakdown and peer comparison."
            )

        elif instrument_sym:
            content = (
                f"**Market Copilot Summary for {instrument_sym}:**\n\n"
                f"- **Current Reference Price:** {price_str}\n"
                f"- **Exchange:** {context_data.get('instrument', {}).get('exchange_code', 'NSE/NASDAQ')}\n"
                f"- **Sector:** {context_data.get('instrument', {}).get('sector', 'General Equities')}\n\n"
                "FinPilot AI has processed the historical OHLCV series and deterministic risk metrics. "
                "You can model hypothetical trade scenarios in the **Trade Planner** or execute simulated paper orders in the **Paper Trading** workstation."
            )
        else:
            content = (
                "**FinPilot AI Market Copilot Active:**\n\n"
                "I can assist you with:\n"
                "- **Quantitative Concepts:** P/E, P/B, Beta, Sharpe Ratio, Sortino Ratio, Value at Risk (VaR), Maximum Drawdown.\n"
                "- **Instrument Intelligence:** Fundamental metrics, business models, and balanced Bull/Bear theses for Indian (NSE/BSE) and US (NYSE/NASDAQ) equities.\n"
                "- **Trade Planning:** Determining exact position sizing and risk/reward scenarios based on your account equity.\n\n"
                "What would you like to evaluate?"
            )

        # Validate and sanitize
        _, final_content, _ = validate_and_sanitize_response(content)

        return {
            "content": final_content,
            "citations": citations,
            "prompt_tokens": len(last_message.split()) * 2 + 10,
            "completion_tokens": len(final_content.split()),
            "total_tokens": len(last_message.split()) * 2 + len(final_content.split()) + 10,
            "model_name": "finpilot-deterministic-fallback"
        }

    def generate_research_report(
        self,
        symbol: str,
        company_name: str,
        metrics: Dict[str, Any],
        recent_news: List[Dict[str, Any]]
    ) -> Dict[str, Any]:
        pe = metrics.get("pe_ratio", 25.0)
        roe = metrics.get("roe", 18.0)
        debt_to_equity = metrics.get("debt_to_equity", 0.4)
        beta = metrics.get("beta", 1.05)

        bull_thesis = [
            f"Strong industry position with sustained Return on Equity (ROE) of {roe:.1f}%.",
            "Robust free cash flow generation enabling self-funded capital expenditures and shareholder returns.",
            "Long-term structural secular tailwinds in core product lines and geographic expansion.",
            "Operating leverage benefits expected as fixed-cost modernization initiatives mature."
        ]

        bear_thesis = [
            f"Current valuation multiple of {pe:.1f}x P/E leaves minimal safety margin for earnings misses.",
            f"Beta of {beta:.2f} implies higher volatility than the overall benchmark index during broader market sell-offs.",
            "Competitive intensity from domestic and international peers compressing gross margins.",
            "Potential macroeconomic deceleration impacting corporate customer discretionary budgets."
        ]

        risk_factors = [
            "Regulatory scrutiny and changes in sector taxation or compliance standards.",
            "Currency and foreign exchange fluctuation impact on international revenues.",
            "Key supplier concentration and input cost inflation."
        ]

        data_warnings = [
            "Financial statements reflect latest public reporting period. Always verify subsequent regulatory filings before making trading decisions.",
            "Historical financial performance is not an indicator or guarantee of future corporate earnings."
        ]

        return {
            "title": f"Institutional Equity Research Report: {company_name} ({symbol})",
            "company_overview": (
                f"{company_name} ({symbol}) is a premier enterprise operating within the financial and commercial marketplace. "
                "The organization maintains established distribution networks, high customer retention, and substantial balance sheet resilience."
            ),
            "business_model": (
                "The firm generates recurring top-line revenue through enterprise contracts, consumer product sales, and service retainers. "
                "High barriers to entry and proprietary intellectual property protect core gross operating margins."
            ),
            "bull_thesis": bull_thesis,
            "bear_thesis": bear_thesis,
            "risk_factors": risk_factors,
            "financial_analysis": (
                f"Financial health remains solid with a Debt-to-Equity ratio of {debt_to_equity:.2f} and Return on Equity (ROE) of {roe:.1f}%. "
                f"Valuation is currently standing at {pe:.1f}x P/E."
            ),
            "technical_summary": (
                f"Price action demonstrates consolidation near key moving average support. "
                f"Calculated beta stands at {beta:.2f}, indicating responsive participation in broader market trends."
            ),
            "data_quality_warnings": data_warnings,
            "metrics_snapshot": metrics,
            "sources": [
                {
                    "title": f"Audited Annual Financial Statements - {symbol}",
                    "source_type": "official_regulatory_filing",
                    "timestamp_retrieved": datetime.now(timezone.utc).isoformat(),
                    "confidence_score": 1.0
                },
                {
                    "title": f"Exchange Master Feed - {symbol}",
                    "source_type": "market_exchange",
                    "timestamp_retrieved": datetime.now(timezone.utc).isoformat(),
                    "confidence_score": 1.0
                }
            ],
            "data_freshness_label": "HISTORICAL / DEMO REPORT"
        }
